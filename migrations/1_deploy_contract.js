const fs = require("fs");
const path = require("path");

// artifacts.require takes the CONTRACT name (FinTechVault), not the file name (SmartContract.sol)
const FinTechVault = artifacts.require("FinTechVault");

module.exports = async function (deployer, network) {
  await deployer.deploy(FinTechVault);
  const vault = await FinTechVault.deployed();

  // `truffle test` also runs migrations; don't point the frontend at a throwaway test deployment.
  if (process.argv.includes("test")) return;

  // Write the ABI and deployed address into the frontend so it always
  // talks to the latest deployment (also updated by `truffle migrate --reset`).
  const config = {
    network,
    address: vault.address,
    abi: FinTechVault.abi,
  };
  const outFile = path.join(__dirname, "..", "frontend", "contract-config.js");
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(
    outFile,
    "// Auto-generated by migrations/1_deploy_contract.js. Do not edit by hand.\n" +
      "window.CONTRACT_CONFIG = " + JSON.stringify(config, null, 2) + ";\n"
  );
  console.log("   > Frontend config written to frontend/contract-config.js");
};
